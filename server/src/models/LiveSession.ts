import { Schema, model, Document, Types } from "mongoose";

export type LiveSessionMode = "business_meeting" | "general_meeting" | "live_class";
export type LiveSessionStatus = "active" | "paused" | "ended" | "failed";

/**
 * A LiveSession tracks the lifecycle of a live meeting/class.
 *
 * IMPORTANT (per architecture decision): we do NOT duplicate transcript or
 * summary storage here. A LiveSession is backed by a normal `Recording`
 * document (created with type "meeting"/"lecture" and source "live") whose
 * Transcript.segments are appended to in real time, and whose Summary is
 * generated by the SAME finalizeRecording() pipeline used for uploaded
 * files once the session ends. This means existing RAG, Ask AI, reports,
 * and analytics work on live sessions with zero additional code.
 */
export interface ILiveSession extends Document {
  _id: Types.ObjectId;
  userId: Types.ObjectId;
  recordingId: Types.ObjectId; // the underlying Recording this session writes into
  title: string;
  mode: LiveSessionMode;
  inputLanguage: string; // "auto" or a specific language
  outputLanguage: string; // language segments are translated into for display
  status: LiveSessionStatus;
  startedAt: Date;
  endedAt?: Date;
  errorMessage?: string;
}

const LiveSessionSchema = new Schema<ILiveSession>({
  userId: { type: Schema.Types.ObjectId, ref: "User", required: true, index: true },
  recordingId: { type: Schema.Types.ObjectId, ref: "Recording", required: true, unique: true },
  title: { type: String, required: true },
  mode: { type: String, enum: ["business_meeting", "general_meeting", "live_class"], default: "general_meeting" },
  inputLanguage: { type: String, default: "auto" },
  outputLanguage: { type: String, default: "English" },
  status: { type: String, enum: ["active", "paused", "ended", "failed"], default: "active" },
  startedAt: { type: Date, default: Date.now },
  endedAt: { type: Date },
  errorMessage: { type: String },
});

export const LiveSession = model<ILiveSession>("LiveSession", LiveSessionSchema);
